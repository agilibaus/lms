    /**
     * L'icona, pronta da scrivere nella pagina. Un nome sconosciuto e' un
     * errore di chi scrive la vista, e lo si vede subito.
     */
    public static function svg(string $nome, string $classe = ''): string
    {
        if (!isset(self::ICONE[$nome])) {
            throw new \InvalidArgumentException('Icona sconosciuta: ' . $nome);
        }

        return '<svg class="icona icona-' . $nome . ($classe !== '' ? ' ' . htmlspecialchars($classe) : '') . '"'
            . ' xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" fill="currentColor"'
            . ' aria-hidden="true" focusable="false">' . self::ICONE[$nome] . '</svg>';
    }

    /** @return list<string> i nomi disponibili (per i test) */
    public static function nomi(): array
    {
        return array_keys(self::ICONE);
    }
